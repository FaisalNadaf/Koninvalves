/**
 * Writes src/data/imageSizes.ts — the intrinsic width/height of every image in
 * public/img. Consumed by <Img> so each <img> carries explicit dimensions and
 * the browser reserves the right box before the file arrives (no layout shift).
 *
 * Run after the image pipeline:  node scripts/gen-image-sizes.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const BASE = path.join(ROOT, 'public', 'img')

const sizes = {}

async function walk(dir) {
  for (const entry of fs.readdirSync(path.join(BASE, dir), { withFileTypes: true })) {
    const rel = dir ? `${dir}/${entry.name}` : entry.name
    if (entry.isDirectory()) {
      await walk(rel)
      continue
    }
    if (!/\.(webp|png|jpe?g|avif)$/i.test(entry.name)) continue
    try {
      const meta = await sharp(path.join(BASE, rel)).metadata()
      sizes[`/img/${rel}`] = [meta.width, meta.height]
    } catch {
      /* unreadable file — skip rather than emit a bad entry */
    }
  }
}

await walk('')

const body = Object.keys(sizes)
  .sort()
  .map((k) => `  '${k}': [${sizes[k][0]}, ${sizes[k][1]}],`)
  .join('\n')

const out = `/**
 * AUTO-GENERATED by scripts/gen-image-sizes.mjs — do not edit by hand.
 * Intrinsic dimensions of every image in /public/img.
 */
export const imageSizes: Record<string, [number, number]> = {
${body}
}

export function sizeOf(src: string): { width?: number; height?: number } {
  const d = imageSizes[src]
  return d ? { width: d[0], height: d[1] } : {}
}
`

fs.writeFileSync(path.join(ROOT, 'src', 'data', 'imageSizes.ts'), out)
console.log(`wrote ${Object.keys(sizes).length} image dimensions`)
